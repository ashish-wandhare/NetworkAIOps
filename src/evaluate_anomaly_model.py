
import json
from pathlib import Path

import mlflow
import mlflow.sklearn
import pandas as pd
from sklearn.ensemble import IsolationForest
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
)
from sklearn.model_selection import train_test_split


# Project paths
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATA_FILE = PROJECT_ROOT / "data" / "telemetry_evaluation.jsonl"
MLFLOW_DB = PROJECT_ROOT / "mlflow.db"

# Features used for anomaly detection
FEATURES = [
    "latency_ms",
    "packet_loss_pct",
    "bandwidth_mbps",
    "interface_errors",
]

# Experiment configurations
CONTAMINATION_VALUES = [0.05, 0.10, 0.15, 0.20]
RANDOM_STATE = 42
TEST_SIZE = 0.20
N_ESTIMATORS = 100


def evaluate_predictions(actual, predicted):
    """Calculate binary anomaly detection metrics."""

    tn, fp, fn, tp = confusion_matrix(
        actual,
        predicted,
        labels=[0, 1],
    ).ravel()

    return {
        "accuracy": float(accuracy_score(actual, predicted)),
        "precision": float(
            precision_score(actual, predicted, zero_division=0)
        ),
        "recall": float(
            recall_score(actual, predicted, zero_division=0)
        ),
        "f1_score": float(
            f1_score(actual, predicted, zero_division=0)
        ),
        "true_positives": int(tp),
        "false_negatives": int(fn),
        "false_positives": int(fp),
        "true_negatives": int(tn),
    }


def main():
    # Load synthetic telemetry dataset
    events = []

    with open(DATA_FILE, "r", encoding="utf-8-sig") as file:
        for line in file:
            if line.strip():
                events.append(json.loads(line))

    df = pd.DataFrame(events)

    if df.empty:
        raise ValueError(f"No events found in {DATA_FILE}")

    required = FEATURES + ["anomaly_type"]
    missing = [
        column for column in required
        if column not in df.columns
    ]

    if missing:
        raise ValueError(f"Missing required columns: {missing}")

    X = df[FEATURES].astype(float)
    y = (df["anomaly_type"] != "none").astype(int)

    if y.nunique() < 2:
        raise ValueError(
            "Dataset must contain both normal and anomalous events."
        )

    # Reproducible train/test split
    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=TEST_SIZE,
        random_state=RANDOM_STATE,
        stratify=y,
    )

    actual = y_test.to_numpy()

    # Local SQLite tracking backend
    tracking_uri = MLFLOW_DB.resolve().as_uri()
    tracking_uri = tracking_uri.replace("file:", "sqlite:", 1)

    mlflow.set_tracking_uri(tracking_uri)
    mlflow.set_experiment("NetworkAIOps-Anomaly-Detection")

    print(f"Total events: {len(df)}")
    print(f"Training events: {len(X_train)}")
    print(f"Testing events: {len(X_test)}")
    print(f"Injected test anomalies: {int(actual.sum())}")
    print(f"MLflow database: {MLFLOW_DB}")

    for contamination in CONTAMINATION_VALUES:
        run_name = (
            f"isolation-forest-contamination-{contamination:.2f}"
        )

        with mlflow.start_run(run_name=run_name):
            model = IsolationForest(
                n_estimators=N_ESTIMATORS,
                contamination=contamination,
                random_state=RANDOM_STATE,
            )

            model.fit(X_train)

            predicted = (
                model.predict(X_test) == -1
            ).astype(int)

            metrics = evaluate_predictions(actual, predicted)

            # Log experiment parameters
            mlflow.log_params({
                "algorithm": "IsolationForest",
                "n_estimators": N_ESTIMATORS,
                "contamination": contamination,
                "random_state": RANDOM_STATE,
                "test_size": TEST_SIZE,
                "features": ",".join(FEATURES),
                "dataset_events": len(df),
                "training_events": len(X_train),
                "testing_events": len(X_test),
            })

            # Log evaluation metrics
            mlflow.log_metrics(metrics)

            # Prepare model signature and example input
            input_example = X_train.head(5)
            signature = mlflow.models.infer_signature(
                X_train,
                model.predict(X_train),
            )

            # Log the model artifact.
            # Trust only the specific scikit-learn tree type
            # generated by this locally trained Isolation Forest.
            mlflow.sklearn.log_model(
                sk_model=model,
                name="isolation_forest_model",
                signature=signature,
                input_example=input_example,
                skops_trusted_types=[
                    "sklearn.tree._tree.Tree"
                ],
            )

            print(f"\n--- {run_name} ---")

            for name, value in metrics.items():
                print(f"{name}: {value}")

            print(
                "MLflow run ID:",
                mlflow.active_run().info.run_id,
            )
            print("Model artifact logged successfully.")

    print("\nAll four experiments completed.")
    print(f"Tracking database: {MLFLOW_DB}")
    print("Existing joblib model was not modified.")


if __name__ == "__main__":
    main()
